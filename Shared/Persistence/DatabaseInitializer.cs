using Microsoft.EntityFrameworkCore;
using System.Text.RegularExpressions;

namespace Tourbooking.Distributed;

// Only the separate initialization job receives a credential with DDL rights.
public static class DatabaseInitializer
{
    public static async Task InitializeAsync(ApplicationDbContext db, CancellationToken ct = default)
    {
        if (!db.Database.IsSqlServer())
        {
            await db.Database.EnsureCreatedAsync(ct);
            if (db.Database.IsSqlite())
            {
                await db.Database.OpenConnectionAsync(ct);
                await using var command = db.Database.GetDbConnection().CreateCommand();
                command.CommandText = "PRAGMA table_info('Bookings')";
                var columns = new HashSet<string>();
                await using (var reader = await command.ExecuteReaderAsync(ct))
                    while (await reader.ReadAsync(ct)) columns.Add(reader.GetString(1));
                foreach (var column in new[] { "SeatReservationId", "SeatReservationToRelease", "SeatReservationState", "SeatPreviousTravelDate" })
                    if (columns.Count > 0 && !columns.Contains(column))
                    {
                        command.CommandText = $"ALTER TABLE Bookings ADD COLUMN {column} TEXT NULL";
                        await command.ExecuteNonQueryAsync(ct);
                    }
            }
            return;
        }
        // Provisioning creates the database first. Bootstrap creates missing objects and
        // applies only the additive snapshot columns below, never legacy shared-DB migrations.
        var script = GenerateSchemaScript(db);
        await using var transaction = await db.Database.BeginTransactionAsync(ct);
        foreach (var batch in Regex.Split(script, @"^GO\s*$", RegexOptions.Multiline))
        {
            if (string.IsNullOrWhiteSpace(batch)) continue;
            const string qualifiedName = @"(?:\[\w+\]\.)?\[\w+\]";
            var table = Regex.Match(batch, @"CREATE TABLE (?<table>" + qualifiedName + ")");
            var index = Regex.Match(batch, @"CREATE (?:UNIQUE )?INDEX \[(?<index>\w+)\] ON (?<table>" + qualifiedName + ")");
            // Names are generated by the EF model, never taken from a request.
            var command = table.Success
                ? $"IF OBJECT_ID(N'{table.Groups["table"].Value}', N'U') IS NULL BEGIN\n{batch}\nEND"
                : index.Success
                    ? $"IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'{index.Groups["index"].Value}' AND object_id = OBJECT_ID(N'{index.Groups["table"].Value}')) BEGIN\n{batch}\nEND"
                    : batch;
            await db.Database.ExecuteSqlRawAsync(command, ct);
        }
        var bookingEntity = db.Model.FindEntityType(typeof(Tourbooking.Models.Booking))!;
        var bookingSchema = bookingEntity.GetSchema() ?? "dbo";
        var bookingTable = $"[{bookingSchema}].[Bookings]";
        foreach (var (column, type) in new[] { ("TourNameSnapshot", "nvarchar(300)"), ("TourLocationSnapshot", "nvarchar(300)"),
            ("DepartureTimeSnapshot", "time"), ("ReturnTimeSnapshot", "time"),
            ("SeatReservationId", "uniqueidentifier"), ("SeatReservationToRelease", "uniqueidentifier"), ("SeatReservationState", "nvarchar(16)"), ("SeatPreviousTravelDate", "datetime2") })
        {
            var addColumn = $"IF OBJECT_ID(N'{bookingSchema}.Bookings', N'U') IS NOT NULL AND COL_LENGTH('{bookingSchema}.Bookings', '{column}') IS NULL ALTER TABLE {bookingTable} ADD [{column}] {type} NULL;";
            await db.Database.ExecuteSqlRawAsync(addColumn, ct);
        }
        await transaction.CommitAsync(ct);
    }

    public static string GenerateSchemaScript(ApplicationDbContext db)
    {
        var script = db.Database.GenerateCreateScript();
        foreach (var fk in db.Model.GetEntityTypes().SelectMany(e => e.GetForeignKeys()))
        {
            if (ServiceData.IsOwned(db.EventSource, fk.DeclaringEntityType) &&
                ServiceData.IsOwned(db.EventSource, fk.PrincipalEntityType)) continue;
            // Relationships to local HTTP read models are query navigation only.
            // They must not constrain deletes/refreshes or masquerade as owner FKs.
            script = Regex.Replace(script, @"^\s*CONSTRAINT \[" +
                Regex.Escape(fk.GetConstraintName()!) + @"\] FOREIGN KEY[^\r\n]*\r?\n", "", RegexOptions.Multiline);
        }
        script = Regex.Replace(script, @",\r?\n(\s*\);)", "\n$1");
        return script;
    }
}
